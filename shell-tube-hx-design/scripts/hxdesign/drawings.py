"""TEMA fabrication drawings as SVG: general arrangement, tubesheet layout, baffle/joint
details with bill of materials, and the TEMA specification sheet.

Convention: the tube-side fluid enters the FRONT channel (N1); the shell-side fluid enters
at the REAR end (N3) and leaves at the front (N4), i.e. counter-flow.
"""
from __future__ import annotations

import math
from datetime import date

from .layout import lattice
from .svg import SVG

INCH = 0.0254
SCALES = [2, 2.5, 4, 5, 10, 15, 20, 25, 30, 40, 50]
# ASME B16.5 Class 150 flange (OD mm, thickness mm) - approximate, for drawing only
FL150 = {1: (108, 14), 1.5: (127, 17), 2: (152, 19), 3: (191, 24), 4: (229, 24), 6: (279, 25), 8: (343, 29),
         10: (406, 30), 12: (483, 32), 14: (533, 35), 16: (597, 37), 18: (635, 40), 20: (699, 43),
         24: (813, 48), 30: (985, 60)}


# ---------------------------------------------------------------------------------------------
def _proj(d):
    return d["design"].spec["project"]


def tag(d):
    return _proj(d).get("tag", "E-101")


def dwg_prefix(d):
    return "HX-" + "".join(ch for ch in tag(d) if ch.isalnum())


def tema_designation(d):
    g = d["geom"]
    return f"{d['mech']['tema_type']} {round(g.Ds / INCH):d}-{round(g.L / INCH):d}"


def _names(d):
    return d["design"].tube.name.upper(), d["design"].shell.name.upper()


def _common_fields(d, title2, dwg_suffix, scale, size, sheet):
    pj = _proj(d)
    tn, sn = _names(d)
    cls = d["design"].spec["mechanical"].get("tema_class", "C")
    return {"project": pj.get("name", "")[:70], "title": f"SHELL & TUBE HEAT EXCHANGER ({tn} / {sn})"[:64],
            "title2": title2, "equipment": f"{tag(d)}   TEMA {tema_designation(d)}   CLASS {cls}",
            "dwg": f"{dwg_prefix(d)}-{dwg_suffix}", "rev": str(pj.get("rev", "0")), "scale": scale, "size": size,
            "date": pj.get("date") or date.today().isoformat(), "code": f"ASME VIII-1 / TEMA {cls}", "sheet": sheet,
            "footer": "Generated by the shell-tube-hx-design skill (ht, fluids, thermo). Preliminary - for fabrication review."}


def nozzle_list(d):
    g, m = d["geom"], d["mech"]
    nz = g.noz
    shell_r = g.Ds / 2 + m["shell"]["t"]

    def proj(n, r):
        return math.ceil((r + max(0.15, 0.6 * n["OD"])) / 0.025) * 0.025

    out_top = (g.Nb % 2 == 0)
    tn, sn = _names(d)
    rear = m["rear_has_nozzle"]
    rows = [
        ("N1", f"{tn} INLET"[:26], nz["tube_in"], "SS" if m["front_is_ss"] else "CS",
         proj(nz["tube_in"], g.Ds / 2 + m["channel_front"]["t"]), 0, "front channel"),
        ("N2", f"{tn} OUTLET"[:26], nz["tube_out"], "SS" if (m["rear_is_ss"] if rear else m["front_is_ss"]) else "CS",
         proj(nz["tube_out"], g.Ds / 2 + (m["channel_rear"] if rear else m["channel_front"])["t"]), 180,
         "rear channel" if rear else "front channel"),
        ("N3", f"{sn} INLET"[:26], nz["shell_in"], "CS", proj(nz["shell_in"], shell_r), 180, "shell, rear end"),
        ("N4", f"{sn} OUTLET"[:26], nz["shell_out"], "CS", proj(nz["shell_out"], shell_r), 0 if out_top else 180,
         "shell, front end"),
    ]
    small = {"NPS": 1, "OD": 0.0334, "ID": 0.0266, "t": 0.0034, "v": 0.0}
    rows += [("N5", "SHELL VENT", small, "CS", math.ceil((shell_r + 0.15) / 0.025) * 0.025, 0, "3000# cplg + plug"),
             ("N6", "SHELL DRAIN", small, "CS", math.ceil((shell_r + 0.15) / 0.025) * 0.025, 180, "3000# cplg + plug"),
             ("N7", "CHANNEL DRAIN", small, "CS", math.ceil((g.Ds / 2 + 0.15) / 0.025) * 0.025, 180, "rear channel")]
    return [{"mark": a, "service": b, "noz": c, "mat": dd, "proj": e, "orient": o, "loc": loc}
            for a, b, c, dd, e, o, loc in rows]


def _fl(nps):
    return FL150.get(nps) or FL150[min(FL150, key=lambda k: abs(k - nps))]


def _axial(d):
    g, m = d["geom"], d["mech"]
    x = {}
    x["cov_f"] = (0.0, m["cover_front"])
    x["ch_f"] = (x["cov_f"][1], x["cov_f"][1] + m["L_ch_front"])
    x["ts_f"] = (x["ch_f"][1], x["ch_f"][1] + g.t_ts)
    x["ts_r"] = (x["ch_f"][1] + g.L - g.t_ts, x["ch_f"][1] + g.L)
    x["shell"] = (x["ts_f"][1], x["ts_r"][0])
    x["ch_r"] = (x["ts_r"][1], x["ts_r"][1] + m["L_ch_rear"])
    x["cov_r"] = (x["ch_r"][1], x["ch_r"][1] + m["cover_rear"])
    x["baffles"] = [x["ts_r"][0] - g.Bin - k * g.B for k in range(g.Nb)]     # k=0 nearest the shell inlet
    return x


def _positions(d):
    g, m = d["geom"], d["mech"]
    x = _axial(d)
    nl = {n["mark"]: n for n in nozzle_list(d)}
    pos = {"N1": (x["ch_f"][0] + x["ch_f"][1]) / 2}
    pos["N2"] = (x["ch_r"][0] + x["ch_r"][1]) / 2 if m["rear_has_nozzle"] else pos["N1"]
    pos["N3"] = x["ts_r"][0] - (nl["N3"]["noz"]["OD"] / 2 + 0.05)
    pos["N4"] = x["ts_f"][1] + (nl["N4"]["noz"]["OD"] / 2 + 0.05)
    pos["N5"] = x["ts_r"][0] - 0.06
    pos["N6"] = x["ts_f"][1] + 0.06 if nl["N4"]["orient"] == 0 else x["ts_f"][1] + nl["N4"]["noz"]["OD"] + 0.15
    pos["N7"] = x["ch_r"][1] - 0.06
    if not m["rear_has_nozzle"]:
        pos["N1"] = x["ch_f"][0] + 0.45 * (x["ch_f"][1] - x["ch_f"][0])
        pos["N2"] = pos["N1"]
    mid = 0.5 * (x["shell"][0] + x["shell"][1])
    bx = sorted(x["baffles"])
    spaces = [(a + b) / 2 for a, b in zip(bx[:-1], bx[1:])] or [mid]
    pos["bellows"] = min(spaces, key=lambda s: abs(s - mid))
    Ls = x["shell"][1] - x["shell"][0]
    s1 = x["shell"][0] + max(0.2 * Ls, 0.25)
    s2 = x["shell"][1] - max(0.2 * Ls, 0.25)
    for mk in ("N3", "N4", "N6"):
        if nl[mk]["orient"] == 180:
            half = _fl(nl[mk]["noz"]["NPS"])[0] / 2e3
            if abs(s1 - pos[mk]) < half + 0.12:
                s1 = pos[mk] + (half + 0.14)
            if abs(s2 - pos[mk]) < half + 0.12:
                s2 = pos[mk] - (half + 0.14)
    pos["saddle_fixed"], pos["saddle_sliding"] = s1, s2
    return x, pos, nl


# ===============================================================================================
def ga_drawing(d, path):
    g, m, lay, D = d["geom"], d["mech"], d["layout"], d["design"]
    x, pos, nl = _positions(d)
    W, H = 841, 594
    sv = SVG(W, H, f"{tag(d)} General Arrangement")
    X0, Y0, X1, Y1 = sv.frame()
    shell_t = m["shell"]["t"]
    ODs = g.Ds + 2 * shell_t
    flOD = m["flange"]["OD"]
    H_cl = math.ceil((ODs / 2 + 0.30) / 0.05) * 0.05
    top_ext = max(n["proj"] + _fl(n["noz"]["NPS"])[1] / 1e3 for n in nl.values() if n["orient"] == 0)
    total = x["cov_r"][1]
    den = SCALES[-1]
    for den in SCALES:
        if total * 1000 / den <= 545 and (top_ext + H_cl) * 1000 / den <= 230:
            break
    k = 1000 / den
    ox, oy = X0 + 45, Y0 + 42 + top_ext * k
    XX = lambda xm: ox + xm * k
    YY = lambda rm: oy - rm * k
    tn, sn = _names(d)

    sv.text(X0 + 5, Y0 + 9, "GENERAL ARRANGEMENT", 6, weight="bold")
    sv.text(X0 + 5, Y0 + 15, f"TEMA {tema_designation(d)} - fixed tubesheets, removable channel covers"
            + (", shell expansion joint" if m["expansion_joint"] else ""), 3.2)
    sv.line(XX(-0.08), YY(0), XX(total + 0.08), YY(0), "center")
    for key, ss in (("cov_f", m["front_is_ss"]), ("cov_r", m["rear_is_ss"])):
        a, b = x[key]
        sv.rect(XX(a), YY(flOD / 2), (b - a) * k, flOD * k, "hatchss" if ss else "hatch")
    fl_t = m["flange"]["t"]
    for key, tch, ss in (("ch_f", m["channel_front"]["t"], m["front_is_ss"]), ("ch_r", m["channel_rear"]["t"], m["rear_is_ss"])):
        a, b = x[key]
        cls = "hatchss" if ss else "hatch"
        for sgn in (1, -1):
            r_in = g.Ds / 2
            sv.rect(XX(a + fl_t), YY(sgn * (r_in + tch)) if sgn > 0 else YY(-r_in), (b - a - 2 * fl_t) * k, tch * k, cls)
            for xa in (a, b - fl_t):
                y_top = flOD / 2 if sgn > 0 else -g.Ds / 2
                sv.rect(XX(xa), YY(y_top), fl_t * k, (flOD / 2 - g.Ds / 2) * k, cls)
    for key in ("ts_f", "ts_r"):
        a, b = x[key]
        sv.rect(XX(a), YY(flOD / 2), (b - a) * k, flOD * k, "hatch")
    if m["hot_tube_inlet"]:
        a = x["ts_f"][0]
        sv.rect(XX(a) - 0.05 * k, YY(g.Ds / 2 - 0.01), 0.05 * k, (g.Ds - 0.02) * k, "refr")
    # shell + bellows
    a, b = x["shell"]
    bel = pos["bellows"]
    bw = 0.16 if m["expansion_joint"] else 0.0
    for sgn in (1, -1):
        ytop = YY(sgn * (g.Ds / 2 + shell_t)) if sgn > 0 else YY(-g.Ds / 2)
        sv.rect(XX(a), ytop, (bel - bw / 2 - a) * k, shell_t * k, "hatch")
        sv.rect(XX(bel + bw / 2), ytop, (b - bel - bw / 2) * k, shell_t * k, "hatch")
    conv_h = 0.07
    if m["expansion_joint"]:
        for sgn in (1, -1):
            r0 = ODs / 2
            dpath = f"M{XX(bel - bw / 2):.2f},{YY(sgn * r0):.2f}"
            pitch = bw / 3
            for i in range(3):
                xs = bel - bw / 2 + i * pitch
                dpath += (f" L{XX(xs):.2f},{YY(sgn * r0):.2f} A{pitch / 2 * k:.2f},{conv_h * k:.2f} 0 0 "
                          f"{1 if sgn > 0 else 0} {XX(xs + pitch):.2f},{YY(sgn * r0):.2f}")
            sv.path(dpath, "thick")
            sv.line(XX(bel - bw / 2), YY(sgn * g.Ds / 2), XX(bel + bw / 2), YY(sgn * g.Ds / 2), "thin")
        sv.leader(XX(bel), YY(ODs / 2 + conv_h), XX(bel) + 18, YY(ODs / 2 + conv_h) - 16,
                  f"EXPANSION BELLOWS (SS321), axial capacity >= {m['expansion']['bellows_axial_capacity'] * 1e3:.0f} mm")
    # tubes, baffles, tie rod
    ys = sorted({round(p[1], 5) for p in lay["tubes"]})
    for yv in ys:
        sv.line(XX(x["ts_f"][0]), YY(yv), XX(x["ts_r"][1]), YY(yv), "tube")
    if g.baffle != "NTIW":
        sv.line(XX(x["ts_f"][1]), YY(g.Dotl / 2), XX(x["ts_r"][0]), YY(g.Dotl / 2), "hidden")
        sv.line(XX(x["ts_f"][1]), YY(-g.Dotl / 2), XX(x["ts_r"][0]), YY(-g.Dotl / 2), "hidden")
    bt = max(g.t_baffle * k, 0.7)
    cut_r = g.Ds / 2 - g.cut * g.Ds
    bod = m["baffle_OD"] / 2
    for i, xb in enumerate(x["baffles"]):
        y_a, y_b = (-bod, cut_r) if i % 2 == 0 else (-cut_r, bod)
        sv.rect(XX(xb) - bt / 2, YY(y_b), bt, (y_b - y_a) * k, "grey")
    sv.line(XX(x["ts_f"][1]), YY(-0.25 * g.Ds), XX(x["baffles"][-1]), YY(-0.25 * g.Ds), "hidden")
    if g.Ntp > 1:
        a, b = x["ch_f"]
        sv.rect(XX(a + fl_t), YY(0.005), (b - a - fl_t) * k, 0.01 * k, "solid")
        if g.Ntp > 2:
            a, b = x["ch_r"]
            sv.rect(XX(a), YY(0.005), (b - a - fl_t) * k, 0.01 * k, "solid")

    def draw_nozzle(n, xc, ys_shell):
        nzd = n["noz"]
        fod, ft = _fl(nzd["NPS"])[0] / 1e3, _fl(nzd["NPS"])[1] / 1e3
        sgn = 1 if n["orient"] == 0 else -1
        r_end = n["proj"]
        sv.rect(XX(xc - nzd["OD"] / 2), YY(sgn * r_end) if sgn > 0 else YY(-ys_shell), nzd["OD"] * k,
                (r_end - ys_shell) * k, "med")
        for side in (-1, 1):
            sv.line(XX(xc + side * nzd["ID"] / 2), YY(sgn * ys_shell), XX(xc + side * nzd["ID"] / 2),
                    YY(sgn * (r_end - ft)), "hidden")
        sv.rect(XX(xc - fod / 2), YY(sgn * r_end) if sgn > 0 else YY(-(r_end - ft)), fod * k, ft * k, "hatch")
        sv.line(XX(xc), YY(sgn * (ys_shell - 0.05)), XX(xc), YY(sgn * (r_end + 0.06)), "center")
        sv.balloon(XX(xc + fod / 2), YY(sgn * (r_end - ft / 2)), n["mark"], XX(xc) + (fod / 2) * k + 6,
                   YY(sgn * (r_end + 0.02)))

    ch_r_f = g.Ds / 2 + m["channel_front"]["t"]
    ch_r_r = g.Ds / 2 + m["channel_rear"]["t"]
    draw_nozzle(nl["N1"], pos["N1"], ch_r_f)
    draw_nozzle(nl["N2"], pos["N2"], ch_r_r if m["rear_has_nozzle"] else ch_r_f)
    draw_nozzle(nl["N3"], pos["N3"], ODs / 2)
    draw_nozzle(nl["N4"], pos["N4"], ODs / 2)
    for mk in ("N5", "N6", "N7"):
        n = nl[mk]
        rs = ODs / 2 if mk != "N7" else ch_r_r
        sgn = 1 if n["orient"] == 0 else -1
        sv.rect(XX(pos[mk] - 0.025), YY(sgn * (rs + 0.06)) if sgn > 0 else YY(-rs), 0.05 * k, 0.06 * k, "med")
        sv.balloon(XX(pos[mk]), YY(sgn * (rs + 0.06)), mk, XX(pos[mk]) - 4, YY(sgn * (rs + 0.06)) - sgn * 16)
    for key, lab in (("saddle_fixed", "FIXED SADDLE"), ("saddle_sliding", "SLIDING SADDLE (slotted holes)")):
        xs = pos[key]
        w_top, w_base = 0.15, 0.22
        sv.poly([(XX(xs - w_top / 2), YY(-ODs / 2)), (XX(xs + w_top / 2), YY(-ODs / 2)),
                 (XX(xs + w_top / 2), YY(-H_cl + 0.02)), (XX(xs - w_top / 2), YY(-H_cl + 0.02))], "med")
        sv.rect(XX(xs - w_base / 2), YY(-H_cl + 0.02), w_base * k, 0.02 * k, "solid")
        sv.text(XX(xs), YY(-H_cl) + 4.5, lab, 2.5, "middle")
    sv.line(XX(-0.05), YY(-H_cl), XX(total + 0.05), YY(-H_cl), "thin")
    sv.text(XX(-0.05) + 1, YY(-H_cl) - 1, "T.O. FOUNDATION", 2.2)
    # dimensions
    yd = YY(-H_cl) + 12
    sv.dim_h(XX(0), XX(total), yd + 18, f"{total * 1e3:.0f} OVERALL", YY(-flOD / 2), YY(-flOD / 2))
    sv.dim_h(XX(x["ts_f"][0]), XX(x["ts_r"][1]), yd + 9, f"{g.L * 1e3:.0f} TUBE LENGTH (O/S TUBESHEETS)",
             YY(-flOD / 2), YY(-flOD / 2))
    sv.dim_h(XX(x["ch_f"][0]), XX(x["ch_f"][1]), yd, f"{m['L_ch_front'] * 1e3:.0f}", YY(-flOD / 2), YY(-flOD / 2))
    sv.dim_h(XX(x["ch_r"][0]), XX(x["ch_r"][1]), yd, f"{m['L_ch_rear'] * 1e3:.0f}", YY(-flOD / 2), YY(-flOD / 2))
    datum = x["ts_f"][0]
    sv.dim_h(XX(datum), XX(pos["saddle_fixed"]), yd, f"{(pos['saddle_fixed'] - datum) * 1e3:.0f}", YY(-H_cl), YY(-H_cl))
    sv.dim_h(XX(pos["saddle_fixed"]), XX(pos["saddle_sliding"]), yd,
             f"{(pos['saddle_sliding'] - pos['saddle_fixed']) * 1e3:.0f} SADDLE CRS", YY(-H_cl), YY(-H_cl))
    ya = YY(top_ext) - 4
    for mk in ("N4", "N3"):
        sv.dim_h(XX(datum), XX(pos[mk]), ya, f"{mk}: {(pos[mk] - datum) * 1e3:.0f}", None, None, size=2.6)
        ya -= 6
    sv.text(XX(datum) + 1, yd + 30, "DATUM: FRONT TUBESHEET O/S FACE (nozzle & saddle locations)", 2.2)
    yb = YY(g.Ds / 2) + 4
    bx = sorted(x["baffles"])
    sv.dim_h(XX(x["shell"][0]), XX(bx[0]), yb, f"{g.Bout * 1e3:.0f}", None, None, size=2.4)
    if len(bx) > 1:
        sv.dim_h(XX(bx[0]), XX(bx[1]), yb, f"{g.B * 1e3:.0f} TYP.", None, None, size=2.4)
    sv.dim_h(XX(bx[-1]), XX(x["shell"][1]), yb, f"{g.Bin * 1e3:.0f}", None, None, size=2.4)
    sv.dim_v(XX(total) + 12, YY(0), YY(-H_cl), f"{H_cl * 1e3:.0f}", XX(total), XX(total))
    n1 = nl["N1"]
    sv.dim_v(XX(0) - 8, YY(0), YY(n1["proj"]), f"{n1['proj'] * 1e3:.0f}", XX(pos["N1"]), XX(pos["N1"]))
    xl = x["shell"][0] + 0.15 * (x["shell"][1] - x["shell"][0])
    sv.leader(XX(xl), YY(ODs / 2), XX(xl) + 10, YY(ODs / 2) - 14,
              f"SHELL ID {g.Ds * 1e3:.0f} x {shell_t * 1e3:.0f} THK  SA-516-70")
    if m["hot_tube_inlet"]:
        sv.leader(XX(x["ts_f"][0]) - 0.025 * k, YY(-0.1 * g.Ds), XX(x["ts_f"][0]) - 8, YY(-0.32 * g.Ds),
                  "CERAMIC FERRULES + 50 REFRACTORY", size=2.4, anchor="end")
    sv.leader(XX(bx[len(bx) // 2]), YY(-0.3 * g.Ds), XX(bx[len(bx) // 2]) - 10, YY(-0.3 * g.Ds) + 24,
              f"{g.Nb} BAFFLES ({'NO-TUBES-IN-WINDOW' if g.baffle == 'NTIW' else 'SEGMENTAL'}) "
              f"{g.cut * 100:.0f}% CUT x {g.t_baffle * 1e3:.1f} THK", anchor="end")
    sv.leader(XX(x["ts_r"][0] - 0.1), YY(ys[-1]), XX(x["ts_r"][0] - 0.1) - 4, YY(ys[-1]) - 26,
              f"{g.Nt} TUBES {g.Do * 1e3:.2f} OD x {g.tw * 1e3:.2f} AVG WALL", anchor="end")
    sv.text(XX(total / 2), YY(-H_cl) + 46, f"SECTIONAL ELEVATION  (SCALE 1:{den:g})", 3.5, "middle", "bold")
    sv.text(XX(pos["N1"]), YY(n1["proj"]) - 9, f"{tn} IN"[:30], 2.6, "middle", "bold")
    f3 = _fl(nl["N3"]["noz"]["NPS"])[0] / 1e3
    sv.text(XX(pos["N3"] - f3 / 2) - 2, YY(-nl["N3"]["proj"]) + 2, f"{sn} IN"[:30], 2.6, "end", "bold")
    # end view
    cx, cy, ke = X0 + 690, oy, k
    sv.text(cx, Y0 + 9, f"END VIEW FROM CHANNEL (N1) END  1:{den:g}", 3.2, "middle", "bold")
    sv.circle(cx, cy, flOD / 2 * ke, "thick")
    sv.circle(cx, cy, m["flange"]["BC"] / 2 * ke, "center")
    for i in range(m["flange"]["n_bolts"]):
        a = 2 * math.pi * (i + 0.5) / m["flange"]["n_bolts"]
        sv.circle(cx + m["flange"]["BC"] / 2 * ke * math.cos(a), cy + m["flange"]["BC"] / 2 * ke * math.sin(a),
                  m["flange"]["hole"] / 2 * ke, "thin")
    sv.circle(cx, cy, ODs / 2 * ke, "hidden")
    sv.line(cx - (flOD / 2 + 0.05) * ke, cy, cx + (flOD / 2 + 0.05) * ke, cy, "center")
    sv.line(cx, cy - (top_ext + 0.05) * ke, cx, cy + (H_cl + 0.05) * ke, "center")
    for mk in ("N1", "N2", "N3", "N4"):
        n = nl[mk]
        sgn = -1 if n["orient"] == 0 else 1
        nzd = n["noz"]
        fod, ft = _fl(nzd["NPS"])[0] / 1e3, _fl(nzd["NPS"])[1] / 1e3
        r0 = flOD / 2 if mk in ("N1", "N2") else ODs / 2
        cls = "med" if mk == "N1" or (mk == "N4" and n["orient"] == 0) else "hidden"
        y0, y1 = cy + sgn * r0 * ke, cy + sgn * (n["proj"] - ft) * ke
        if abs(y1 - cy) > abs(y0 - cy):
            sv.rect(cx - nzd["OD"] / 2 * ke, min(y0, y1), nzd["OD"] * ke, abs(y1 - y0), cls)
        sv.rect(cx - fod / 2 * ke, cy + sgn * n["proj"] * ke if sgn < 0 else cy + (n["proj"] - ft) * ke,
                fod * ke, ft * ke, cls)
    top_list = ["N1", "N5"] + (["N4"] if nl["N4"]["orient"] == 0 else [])
    bot_list = ["N2", "N3", "N6", "N7"] + (["N4"] if nl["N4"]["orient"] == 180 else [])
    sv.text(cx + (flOD / 2) * ke + 3, cy - 0.6 * flOD / 2 * ke, "0 deg (top): " + ", ".join(top_list), 2.4)
